Lesson _l(
  String id,
  String course,
  String title,
  String sub,
  String what,
  String why,
  String how,
  String quiz,
  String ok,
  String c1,
  String e1,
  String c2,
  String e2, {
  List<String> wrong = const ['Unrelated', 'The opposite', 'Not how LLMs work'],
  VisualizerType viz = VisualizerType.none,
}) {
  return u(
    id,
    _t,
    course,
    title,
    sub,
    what,
    why,
    how,
    quiz,
    ok,
    wrong: wrong,
    code: c1,
    expected: e1,
    code2: c2,
    expected2: e2,
    visualizer: viz,
  );
}

