Lesson fillPythonPractice(Lesson lesson) {
  var next = lesson;
  var examples = next.runnableExamples;
  if (examples.length == 1) {
    next = next.withPlaygrounds([
      examples.first,
      py('Example 2 — change one value and run again', examples.first.code, expected: examples.first.expectedOutput),
    ]);
    examples = next.runnableExamples;
  }
  if (examples.isEmpty) return next;
  final a = examples.first;
  final b = examples.length > 1 ? examples[1] : a;
  return next.withPractice(
    predictChallenge: next.predictChallenge ??
        PredictChallenge(
          code: a.code,
          expectedOutput: a.expectedOutput,
          explanation: 'Read top to bottom. Each print becomes one line of output.',
        ),
    debugChallenge: next.debugChallenge ??
        CodeExercise(
          title: 'Debug challenge',
          prompt: 'This version is broken. Restore it so the output matches Example 1.',
          starterCode: 'print("TODO")\n# Fix this so it matches Example 1 for "${next.title}".',
          expectedOutput: a.expectedOutput,
          hint: 'Start from Example 1 and restore the real print.',
        ),
    codingChallenge: next.codingChallenge ??
        CodeExercise(
          title: 'Coding challenge',
          prompt: 'Write a short program that uses "${next.title}" and prints a clear result.',
          starterCode: '# Your code here\n',
          expectedOutput: b.expectedOutput,
          hint: 'Use Example 2 as a model, then change one value.',
        ),
    miniProject: next.miniProject ??
        CodeExercise(
          title: 'Mini project',
          prompt: 'Apply "${next.title}" to a tiny real task. Keep it under 15 lines.',
          starterCode: '# Mini project: ${next.title}\n',
          expectedOutput: a.expectedOutput,
          hint: 'Combine the examples into one short script.',
        ),
    quizQuestions: next.quizQuestions.isEmpty
        ? [
            mcq(
              id: 'q_${next.id}',
              question: 'The fastest way to lock "${next.title}" is to',
              options: [
                opt('1', 'Write a tiny example and run it', true),
                opt('2', 'Only highlight the heading', false),
                opt('3', 'Skip to a framework wrap', false),
              ],
              explanation: 'A tiny example is the contract. Frameworks come after.',
              topic: next.title,
            ),
          ]
        : null,
  );
}

RoadmapTrack applyPythonLabs(RoadmapTrack track) {
  if (track.id != 'track_python') return track;
  final labs = pythonLabs();
  return track.withModules([
    for (final module in track.modules)
      LearningModule(
        id: module.id,
        trackId: module.trackId,
        title: module.title,
        description: module.description,
        lessons: [
          for (final lesson in module.lessons)
            fillPythonPractice(
              labs.containsKey(lesson.id) ? lesson.withPlaygrounds(labs[lesson.id]!) : lesson,
            ),
        ],
      ),
  ]);
}
